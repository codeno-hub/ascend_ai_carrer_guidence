interface TimelineItemProps {
  key?: string | number;
  step: { action: string; detail: string };
  index: number;
  totalIndex: number;
  type: 'short' | 'long';
  isLast?: boolean;
}

const TimelineItem = ({ step, index, totalIndex, type, isLast }: TimelineItemProps) => {
  const [isExpanded, setIsExpanded] = useState(false);

  return (
    <motion.div 
      initial={{ opacity: 0, x: -10 }}
      animate={{ opacity: 1, x: 0 }}
      transition={{ delay: totalIndex * 0.1 }}
      className="relative flex gap-6 group"
    >
      <button 
        onClick={() => setIsExpanded(!isExpanded)}
        className={`z-10 shrink-0 w-8 h-8 rounded-full flex items-center justify-center font-bold text-[10px] shadow-sm transition-all duration-300 ring-4 ring-white ${
          type === 'short' 
            ? 'bg-white border-2 border-app-accent text-app-accent hover:bg-app-accent hover:text-white' 
            : 'bg-indigo-900 border-2 border-indigo-700 text-white hover:bg-indigo-800'
        }`}
      >
        {totalIndex + 1}
      </button>
      
      <div 
        className={`flex-1 p-4 rounded-xl border transition-all cursor-pointer ${
          isExpanded 
            ? (type === 'short' ? 'bg-white border-[rgba(79,70,229,0.3)] shadow-md' : 'bg-indigo-50 border-indigo-200 shadow-md')
            : (type === 'short' ? 'bg-app-slate-subtle border-slate-100 hover:border-[rgba(79,70,229,0.2)]' : 'bg-[rgba(238,242,255,0.2)] border-[rgba(238,242,255,0.5)] hover:border-indigo-100')
        }`}
        onClick={() => setIsExpanded(!isExpanded)}
      >
        <div className="flex justify-between items-start gap-4">
          <p className={`text-xs leading-relaxed ${type === 'long' ? 'font-medium' : ''}`}>
            {step.action}
          </p>
          <motion.div
            animate={{ rotate: isExpanded ? 180 : 0 }}
            className="shrink-0 pt-0.5"
          >
            <ChevronDown className={`w-3.5 h-3.5 ${type === 'short' ? 'text-app-accent' : 'text-indigo-600'}`} />
          </motion.div>
        </div>

        <AnimatePresence>
          {isExpanded && (
            <motion.div
              initial={{ height: 0, opacity: 0 }}
              animate={{ height: 'auto', opacity: 1 }}
              exit={{ height: 0, opacity: 0 }}
              className="overflow-hidden"
            >
              <div className="pt-3 mt-3 border-t border-slate-100">
                <p className="text-[11px] text-app-text-secondary leading-relaxed italic">
                  {step.detail}
                </p>
              </div>
            </motion.div>
          )}
        </AnimatePresence>
      </div>
    </motion.div>
  );
};

