const ShareDialog = ({ roadmap, onClose }: { roadmap: CareerAnalysis, onClose: () => void }) => {
  const shareText = `Check out my personalized AI Career Roadmap for ${roadmap.recommendations[0].title}! Generated by Ascend.`;
  const shareUrl = window.location.href;

  const handleCopyLink = () => {
    navigator.clipboard.writeText(shareUrl);
    alert('Link copied to clipboard!');
  };

  const handleShare = async () => {
    if (navigator.share) {
      try {
        await navigator.share({
          title: 'My AI Career Roadmap',
          text: shareText,
          url: shareUrl,
        });
      } catch (err) {
        console.log('Error sharing:', err);
      }
    } else {
      handleCopyLink();
    }
  };

  return (
    <motion.div 
      initial={{ opacity: 0 }}
      animate={{ opacity: 1 }}
      exit={{ opacity: 0 }}
      className="fixed inset-0 z-[100] flex items-center justify-center p-6 bg-[rgba(15,23,42,0.6)] backdrop-blur-sm"
      onClick={onClose}
    >
      <motion.div 
        initial={{ scale: 0.9, y: 20 }}
        animate={{ scale: 1, y: 0 }}
        className="bg-white rounded-[32px] p-8 max-w-sm w-full shadow-2xl border border-slate-100"
        onClick={e => e.stopPropagation()}
      >
        <h3 className="text-xl font-bold mb-2">Share Roadmap</h3>
        <p className="text-sm text-app-text-secondary mb-8">Share your professional trajectory with your network.</p>
        
        <div className="grid grid-cols-2 gap-4 mb-8">
          <button 
            onClick={() => window.open(`https://twitter.com/intent/tweet?text=${encodeURIComponent(shareText)}&url=${encodeURIComponent(shareUrl)}`)}
            className="flex flex-col items-center gap-3 p-4 bg-slate-50 rounded-2xl hover:bg-app-accent-light hover:text-app-accent transition-all group"
          >
            <Twitter className="w-5 h-5" />
            <span className="text-[10px] font-bold uppercase tracking-widest">Twitter</span>
          </button>
          <button 
            onClick={() => window.open(`https://www.linkedin.com/sharing/share-offsite/?url=${encodeURIComponent(shareUrl)}`)}
            className="flex flex-col items-center gap-3 p-4 bg-slate-50 rounded-2xl hover:bg-app-accent-light hover:text-app-accent transition-all group"
          >
            <Linkedin className="w-5 h-5" />
            <span className="text-[10px] font-bold uppercase tracking-widest">LinkedIn</span>
          </button>
          <button 
            onClick={() => window.open(`mailto:?subject=My Career Roadmap&body=${encodeURIComponent(shareText + "\n\n" + shareUrl)}`)}
            className="flex flex-col items-center gap-3 p-4 bg-slate-50 rounded-2xl hover:bg-app-accent-light hover:text-app-accent transition-all group"
          >
            <Mail className="w-5 h-5" />
            <span className="text-[10px] font-bold uppercase tracking-widest">Email</span>
          </button>
          <button 
            onClick={handleShare}
            className="flex flex-col items-center gap-3 p-4 bg-slate-50 rounded-2xl hover:bg-app-accent-light hover:text-app-accent transition-all group"
          >
            <Share2 className="w-5 h-5" />
            <span className="text-[10px] font-bold uppercase tracking-widest">System</span>
          </button>
        </div>

        <button 
          onClick={handleCopyLink}
          className="w-full flex items-center justify-center gap-2 py-4 bg-slate-100 rounded-xl text-sm font-semibold hover:bg-slate-200 transition-colors"
        >
          <Copy className="w-4 h-4" />
          Copy Direct Link
        </button>
      </motion.div>
    </motion.div>
  );
};

